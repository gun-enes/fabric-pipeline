--Check if sp_infra_generate_table_definition sproc works correct
CREATE PROCEDURE [UnitTests].[test_verification_generate_table_definition_check]
AS
BEGIN
    PRINT ('Executing Test: test_verification_generate_table_definition_check')

    DECLARE @base_table_definition NVARCHAR(MAX);
    DECLARE @table_definition NVARCHAR(MAX);
    DECLARE @table_definition_generated NVARCHAR(MAX);

    -- create a table definiton including all supported data types with various sizes
    SET @base_table_definition =
    '
    IF OBJECT_ID(''[UnitTests].[GenerateTableDef]'') IS NOT NULL
    BEGIN
        DROP TABLE [UnitTests].[GenerateTableDef];
    END
    CREATE TABLE [UnitTests].[GenerateTableDef](
    [col_bigint] [BIGINT] NOT NULL,
    [col_binary] [BINARY](1) NULL,
    [col_bit] [BIT] NULL,
    [col_char] [CHAR](100) NOT NULL,
    [col_date] [DATE] NULL,
    [col_datetime] [DATETIME] NULL,
    [col_datetime2] [DATETIME2](3) NULL,
    [col_datetimeoffset] [DATETIMEOFFSET](3) NULL,
    [col_decimal] [DECIMAL](10,5) NULL,
    [col_float] [FLOAT] NOT NULL,
    [col_int] [INT] NULL,
    [col_nchar] [NCHAR](100) NULL,
    [col_numeric] [NUMERIC](10,5) NULL,
    [col_nvarchar] [NVARCHAR](4000) NULL,
    [col_real] [REAL] NULL,
    [col_smalldatetime] [SMALLDATETIME] NULL,
    [col_smallint] [SMALLINT] NULL,
    [col_money] [MONEY] NULL,
    [col_smallmoney] [SMALLMONEY] NULL,
    [col_sysname] [SYSNAME] NULL,
    [col_time] [TIME](7) NULL,
    [col_tinyint] [TINYINT] NULL,
    [col_uniqueidentifier] [UNIQUEIDENTIFIER] NULL,
    [col_varbinary] [VARBINARY](1) NULL,
    [col_varchar] [VARCHAR](8000) NULL'

    -- test the ROUND_ROBIN and CLUSTERED COLUMNSTORE INDEX table
    SET @table_definition = @base_table_definition +
    '
)
WITH (
    DISTRIBUTION = ROUND_ROBIN,
    CLUSTERED COLUMNSTORE INDEX
);';

    EXEC [sp_executesql] @table_definition;
    -- generate table definition via sproc
    EXEC [mgmt_xtinfra].[sp_infra_generate_table_definition] 'UnitTests', 'GenerateTableDef', 'GenerateTableDef', @table_definition_generated OUTPUT;
    -- compare generated and original table definitions
    EXEC [tSQLt_synapse].[AssertEqualsString] @table_definition, @table_definition_generated;

    -- test the REPLICATE and HEAP table
    SET @table_definition = @base_table_definition +
    ',
    [col_varbinary_max] [VARBINARY](MAX) NOT NULL,
    [col_varchar_max] [VARCHAR](MAX) NOT NULL,
    [col_nvarchar_max] [NVARCHAR](MAX) NOT NULL
)
WITH (
    DISTRIBUTION = REPLICATE,
    HEAP
);';

    EXEC [sp_executesql] @table_definition;
    -- generate table definition via sproc
    EXEC [mgmt_xtinfra].[sp_infra_generate_table_definition] 'UnitTests', 'GenerateTableDef', 'GenerateTableDef', @table_definition_generated OUTPUT;
    -- compare generated and original table definitions
    EXEC [tSQLt_synapse].[AssertEqualsString] @table_definition, @table_definition_generated;

    -- test the HASH and CLUSTERED INDEX table
    SET @table_definition = @base_table_definition +
    '
)
WITH (
    DISTRIBUTION = HASH ([col_bigint]),
    CLUSTERED INDEX ([col_bigint] ASC, [col_bit] DESC)
);';

    EXEC [sp_executesql] @table_definition;
    -- generate table definition via sproc
    EXEC [mgmt_xtinfra].[sp_infra_generate_table_definition] 'UnitTests', 'GenerateTableDef', 'GenerateTableDef', @table_definition_generated OUTPUT;
    -- compare generated and original table definitions
    EXEC [tSQLt_synapse].[AssertEqualsString] @table_definition, @table_definition_generated;

    -- test the CLUSTERED COLUMNSTORE INDEX ORDER table
    SET @table_definition = @base_table_definition +
    '
)
WITH (
    DISTRIBUTION = HASH ([col_bigint]),
    CLUSTERED COLUMNSTORE INDEX ORDER ([col_bigint], [col_bit])
);';

    EXEC [sp_executesql] @table_definition;

    -- the index sorder is not generated by the sproc so, set the expected table definition string after table creation
    SET @table_definition = @base_table_definition +
    '
)
WITH (
    DISTRIBUTION = HASH ([col_bigint]),
    CLUSTERED COLUMNSTORE INDEX
);';

    -- generate table definition via sproc
    EXEC [mgmt_xtinfra].[sp_infra_generate_table_definition] 'UnitTests', 'GenerateTableDef', 'GenerateTableDef', @table_definition_generated OUTPUT;
    -- compare generated and original table definitions
    EXEC [tSQLt_synapse].[AssertEqualsString] @table_definition, @table_definition_generated;
END;
GO

CREATE PROCEDURE [UnitTests].[rollback_test_verification_generate_table_definition_check]
AS
BEGIN
    PRINT ('Executing Rollback: rollback_test_verification_generate_table_definition_check')
    DROP TABLE [UnitTests].[GenerateTableDef]
END;
GO
